"""Address encodings, written from their specifications with the standard library only.

* Keccak-256 (the Keccak team's specification as used by Ethereum). The SHA-3 standard FIPS 202 differs only in the padding byte, which
  is why ``sponge256(data, 0x06)`` equals ``hashlib.sha3_256`` and ``keccak256`` uses ``0x01``. The round constants and rotation offsets
  are generated by the algorithms of FIPS 202 (Algorithm 5 and the rho walk), not typed in.
* EIP-55 mixed-case checksum of an Ethereum address.
* base58 and base58check (Bitcoin and Tron addresses).
* bech32 (BIP-173) and bech32m (BIP-350), and the segregated-witness address rules. The checksum and conversion follow the reference
  Python in those BIPs (BSD-2-Clause, credited in the league's NOTICE.md).
"""

from __future__ import annotations

import hashlib

_MASK = (1 << 64) - 1
_RATE = 136  # bytes absorbed per permutation for a 256-bit output (1600 - 2 * 256 bits)


def _round_constants() -> tuple[int, ...]:
    def rc(t: int) -> int:
        if t % 255 == 0:
            return 1
        r = 1
        for _ in range(t % 255):
            r <<= 1
            if r & 0x100:
                r ^= 0x171  # R[0], R[4], R[5], R[6] take R[8], and R[8] falls off (x^8 + x^6 + x^5 + x^4 + 1)
        return r & 1

    out = []
    for i in range(24):
        value = 0
        for j in range(7):
            if rc(j + 7 * i):
                value |= 1 << ((1 << j) - 1)
        out.append(value)
    return tuple(out)


def _rotations() -> tuple[int, ...]:
    offsets = [0] * 25
    x, y = 1, 0
    for t in range(24):
        offsets[x + 5 * y] = ((t + 1) * (t + 2) // 2) % 64
        x, y = y, (2 * x + 3 * y) % 5
    return tuple(offsets)


_RC = _round_constants()
_ROT = _rotations()


def _rol(value: int, shift: int) -> int:
    return ((value << shift) | (value >> (64 - shift))) & _MASK if shift else value


def _permute(lanes: list[int]) -> None:
    for constant in _RC:
        c = [lanes[x] ^ lanes[x + 5] ^ lanes[x + 10] ^ lanes[x + 15] ^ lanes[x + 20] for x in range(5)]
        d = [c[(x - 1) % 5] ^ _rol(c[(x + 1) % 5], 1) for x in range(5)]
        a = [lanes[i] ^ d[i % 5] for i in range(25)]
        b = [0] * 25
        for x in range(5):
            for y in range(5):
                b[y + 5 * ((2 * x + 3 * y) % 5)] = _rol(a[x + 5 * y], _ROT[x + 5 * y])
        for x in range(5):
            for y in range(5):
                lanes[x + 5 * y] = b[x + 5 * y] ^ (~b[(x + 1) % 5 + 5 * y] & b[(x + 2) % 5 + 5 * y] & _MASK)
        lanes[0] ^= constant


def sponge256(data: bytes, pad: int) -> bytes:
    """The Keccak-f[1600] sponge with a 136-byte rate and a 32-byte output; ``pad`` is the domain byte (0x01 Keccak, 0x06 SHA-3)."""
    padded = bytearray(data)
    padded.append(pad)
    padded.extend(bytes(-len(padded) % _RATE))
    padded[-1] |= 0x80
    lanes = [0] * 25
    for start in range(0, len(padded), _RATE):
        block = padded[start : start + _RATE]
        for i in range(_RATE // 8):
            lanes[i] ^= int.from_bytes(block[8 * i : 8 * i + 8], "little")
        _permute(lanes)
    return b"".join(lane.to_bytes(8, "little") for lane in lanes[:4])


def keccak256(data: bytes) -> bytes:
    return sponge256(data, 0x01)


def eip55(hex40: str) -> str:
    """The EIP-55 form of 40 hex characters (given in lower case), with its 0x prefix."""
    digest = keccak256(hex40.encode("ascii")).hex()
    return "0x" + "".join(ch.upper() if ch.isalpha() and int(digest[i], 16) >= 8 else ch for i, ch in enumerate(hex40))


_B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
_B58_INDEX = {ch: i for i, ch in enumerate(_B58)}


def b58decode(text: str) -> bytes | None:
    """base58 to bytes, each leading '1' a zero byte; None when a character is outside the alphabet."""
    number = 0
    for ch in text:
        digit = _B58_INDEX.get(ch)
        if digit is None:
            return None
        number = number * 58 + digit
    zeros = len(text) - len(text.lstrip("1"))
    body = number.to_bytes((number.bit_length() + 7) // 8, "big")
    return bytes(zeros) + body


def base58check_decode(text: str) -> bytes | None:
    """The payload (version byte included) of a base58check string, or None when the alphabet or the four-byte checksum is wrong."""
    raw = b58decode(text)
    if raw is None or len(raw) < 5:
        return None
    payload, checksum = raw[:-4], raw[-4:]
    if hashlib.sha256(hashlib.sha256(payload).digest()).digest()[:4] != checksum:
        return None
    return payload


_CHARSET = "qpzry9x8gf2tvdw0s3jn54khce6mua7l"
_GENERATOR = (0x3B6A57B2, 0x26508E6D, 0x1EA119FA, 0x3D4233DD, 0x2A1462B3)
_BECH32M_CONST = 0x2BC830A3


def _polymod(values: list[int]) -> int:
    chk = 1
    for value in values:
        top = chk >> 25
        chk = (chk & 0x1FFFFFF) << 5 ^ value
        for i in range(5):
            if (top >> i) & 1:
                chk ^= _GENERATOR[i]
    return chk


def _hrp_expand(hrp: str) -> list[int]:
    return [ord(x) >> 5 for x in hrp] + [0] + [ord(x) & 31 for x in hrp]


def bech32_decode(text: str) -> tuple[str, list[int], str] | None:
    """(human-readable part, data values without the checksum, "bech32" or "bech32m"), or None for anything BIP-173/350 rejects."""
    if any(ord(x) < 33 or ord(x) > 126 for x in text):
        return None
    if text.lower() != text and text.upper() != text:
        return None
    text = text.lower()
    pos = text.rfind("1")
    if pos < 1 or pos + 7 > len(text) or len(text) > 90:
        return None
    if not all(x in _CHARSET for x in text[pos + 1 :]):
        return None
    hrp = text[:pos]
    data = [_CHARSET.find(x) for x in text[pos + 1 :]]
    const = _polymod(_hrp_expand(hrp) + data)
    if const == 1:
        return hrp, data[:-6], "bech32"
    if const == _BECH32M_CONST:
        return hrp, data[:-6], "bech32m"
    return None


def convertbits(data: list[int], frombits: int, tobits: int, pad: bool) -> list[int] | None:
    acc = 0
    bits = 0
    out: list[int] = []
    maxv = (1 << tobits) - 1
    max_acc = (1 << (frombits + tobits - 1)) - 1
    for value in data:
        if value < 0 or value >> frombits:
            return None
        acc = ((acc << frombits) | value) & max_acc
        bits += frombits
        while bits >= tobits:
            bits -= tobits
            out.append((acc >> bits) & maxv)
    if pad:
        if bits:
            out.append((acc << (tobits - bits)) & maxv)
    elif bits >= frombits or (acc << (tobits - bits)) & maxv:
        return None
    return out


def segwit_decode(hrp: str, address: str) -> tuple[int, bytes] | None:
    """(witness version, witness program) of a segregated-witness address under ``hrp``, or None (BIP-173 and BIP-350)."""
    got = bech32_decode(address)
    if got is None or got[0] != hrp:
        return None
    data, spec = got[1], got[2]
    program = convertbits(data[1:], 5, 8, False)
    if program is None or len(program) < 2 or len(program) > 40:
        return None
    version = data[0]
    if version > 16:
        return None
    if version == 0 and len(program) not in (20, 32):
        return None
    if (version == 0) != (spec == "bech32"):
        return None
    return version, bytes(program)
