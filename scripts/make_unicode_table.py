"""Write the table of code points assigned in Unicode 15.0: ``src/hoshitori/unicode15.py`` and ``verifier-js/src/unicode15.mjs``.

The record profile admits a string only if every code point in it is assigned in Unicode 15.0, that is, has a general category other
than Cn (unassigned, which also covers the noncharacters) in the Unicode Character Database 15.0.0. Unicode's normalization stability
policy keeps the NFC form of a string made only of characters assigned in a version the same in every later version, so two runtimes on
Unicode 15.0 or later cannot disagree on whether such a string is NFC (finding D-NFC: Python on 15.0 and Node on 17.0 did disagree on
U+105D2 U+0307, which only Unicode 16.0 and later compose).

The ranges are read here, once, from Python's ``unicodedata`` and written into both verifiers, so that neither reads the repertoire from
its own runtime: a later Python or ICU would widen it without notice. Run from the repository root with a Python whose
``unicodedata.unidata_version`` is 15.0.0 (Python 3.12):

    python scripts/make_unicode_table.py

Any other Unicode version is refused. Every run writes the same bytes.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

VERSION = "15.0.0"
ROOT = Path(__file__).resolve().parents[1]
PYTHON_TABLE = ROOT / "src" / "hoshitori" / "unicode15.py"
NODE_TABLE = ROOT / "verifier-js" / "src" / "unicode15.mjs"
LAST_CODE_POINT = 0x10FFFF


def assigned_ranges() -> list[tuple[int, int]]:
    """Inclusive ranges of the code points whose general category is not Cn, in order, never adjacent."""
    ranges: list[tuple[int, int]] = []
    start: int | None = None
    for code in range(LAST_CODE_POINT + 1):
        assigned = unicodedata.category(chr(code)) != "Cn"
        if assigned and start is None:
            start = code
        elif not assigned and start is not None:
            ranges.append((start, code - 1))
            start = None
    if start is not None:
        ranges.append((start, LAST_CODE_POINT))
    return ranges


def render_python(ranges: list[tuple[int, int]]) -> str:
    lines = [
        '"""The code points assigned in Unicode 15.0: the repertoire of the record profile (``LEDGER_SPEC`` section 2, rule 4).',
        "",
        "Generated by ``scripts/make_unicode_table.py`` from Python's ``unicodedata`` 15.0.0, which is built from the Unicode Character",
        "Database 15.0.0 (see ``NOTICE.md``); do not edit. A code point is assigned when its general category is anything but Cn, so the",
        "noncharacters are not in the table, while surrogates (Cs) and private-use code points (Co) are. ``ASSIGNED`` holds inclusive",
        "ranges, sorted and never adjacent; ``verifier-js/src/unicode15.mjs`` holds the same ranges for the Node verifier.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Final",
        "",
        f'UNICODE_VERSION: Final = "{VERSION}"',
        "ASSIGNED: Final[tuple[tuple[int, int], ...]] = (",
        *(f"    (0x{first:04X}, 0x{last:04X})," for first, last in ranges),
        ")",
        "",
    ]
    return "\n".join(lines)


def render_node(ranges: list[tuple[int, int]]) -> str:
    lines = [
        "// The code points assigned in Unicode 15.0: the repertoire of the record profile (LEDGER_SPEC section 2, rule 4).",
        "// Generated by scripts/make_unicode_table.py from Python's unicodedata 15.0.0, which is built from the Unicode Character",
        "// Database 15.0.0 (see NOTICE.md); do not edit. A code point is assigned when its general category is anything but Cn, so the",
        "// noncharacters are not in the table, while surrogates (Cs) and private-use code points (Co) are. ASSIGNED holds inclusive",
        "// ranges, sorted and never adjacent; src/hoshitori/unicode15.py holds the same ranges for the Python verifier.",
        f'export const UNICODE_VERSION = "{VERSION}";',
        "export const ASSIGNED = Object.freeze([",
        *(f"  Object.freeze([0x{first:04X}, 0x{last:04X}])," for first, last in ranges),
        "]);",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    if unicodedata.unidata_version != VERSION:
        found = unicodedata.unidata_version
        print(f"make_unicode_table: this Python has Unicode {found}; the table is generated from {VERSION} only", file=sys.stderr)
        return 1
    ranges = assigned_ranges()
    PYTHON_TABLE.write_text(render_python(ranges), encoding="utf-8")
    NODE_TABLE.write_text(render_node(ranges), encoding="utf-8")
    count = sum(last - first + 1 for first, last in ranges)
    print(f"wrote {len(ranges)} ranges ({count} assigned code points) to {PYTHON_TABLE} and {NODE_TABLE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
