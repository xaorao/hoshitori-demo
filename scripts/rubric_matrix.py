#!/usr/bin/env python3
"""Write ``RUBRIC_MATRIX.md``: each line of the organisers' published rubric, the page of the product that bears on it, the checks
that hold that page to what it says, and what the page does not show.

The lines, their points, their pages and their limits are read from ``web/src/judges.ts`` (the map the judges page shows, which a web test
holds to the published rubric). The checks are named in ``docs/rubric_evidence.json``; a name is looked for as a test or check function, a
test file or a script in the repository, as ``scripts/proof_matrix.py`` looks for the invariants' tests. A line with no check, a check that
cannot be found or a line that is not in the map is an error. The page says a check exists; it does not run it.

Usage: python scripts/rubric_matrix.py [OUT.md]
"""

from __future__ import annotations

import json
import re
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Final

REPO: Final = Path(__file__).resolve().parents[1]
DEFAULT_OUT: Final = REPO / "docs" / "specs" / "RUBRIC_MATRIX.md"
SEARCH_DIRS: Final = ("tests", "verifier-js/test", "settlement-js/test", "web/test", "web/tools", "skills")
ENTRY: Final = re.compile(
    r'group:\s*"(?P<group>[a-z]+)",\s*line:\s*"(?P<line>[^"]+)",\s*points:\s*(?P<points>\d+),\s*where:\s*\{\s*page:\s*"(?P<page>[a-z]+)"[^}]*\},'
    r'\s*look:\s*"(?P<look>(?:[^"\\]|\\.)*)",\s*limit:\s*"(?P<limit>(?:[^"\\]|\\.)*)"',
    re.S,
)
VERDICTS: Final = ("CHECKS FOUND", "CHECK NOT FOUND", "NO CHECK NAMED")
TRACK_NAMES: Final = {
    "common": "Every track",
    "agents": "Autonomous Agents",
    "interfaces": "Dashboards and Interfaces",
    "skills": "New Skills",
}


class RubricError(ValueError):
    """Evidence that does not fit the map."""


@dataclass(frozen=True)
class Line:
    group: str
    line: str
    points: int
    page: str
    look: str
    limit: str


@dataclass(frozen=True)
class Judged:
    line: Line
    verdict: str
    found: tuple[str, ...] = ()
    missing: tuple[str, ...] = ()


def read_lines(text: str) -> list[Line]:
    """The lines of the judges map, in the order the rubric gives them."""
    return [
        Line(m["group"], m["line"], int(m["points"]), m["page"], m["look"].replace('\\"', '"'), m["limit"].replace('\\"', '"'))
        for m in ENTRY.finditer(text)
    ]


def _haystack(root: Path) -> tuple[str, set[str]]:
    text: list[str] = []
    stems: set[str] = set()
    for folder in SEARCH_DIRS:
        base = root / folder
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if path.suffix in (".py", ".mjs", ".ts", ".tsx") and ".venv" not in path.parts and "node_modules" not in path.parts:
                stems.add(path.stem)
                text.append(path.read_text(encoding="utf-8", errors="ignore"))
    return "\n".join(text), stems


def judge(lines: Sequence[Line], evidence: Mapping[str, Sequence[str]], root: Path) -> list[Judged]:
    known = {x.line for x in lines}
    for name in evidence:
        if name not in known:
            raise RubricError(f"{name!r} is not a line of the rubric")
    text, stems = _haystack(root)
    out: list[Judged] = []
    for x in lines:
        names = list(evidence.get(x.line, ()))
        if any(not isinstance(n, str) or not n.strip() for n in names):
            raise RubricError("a check is a name")
        found: list[str] = []
        missing: list[str] = []
        for name in names:
            key = name.split(".")[-1]
            ok = name in stems or key in stems or re.search(rf"\b{re.escape(key)}\b", text) is not None
            (found if ok else missing).append(name)
        if not names:
            out.append(Judged(x, "NO CHECK NAMED"))
        elif missing:
            out.append(Judged(x, "CHECK NOT FOUND", tuple(found), tuple(missing)))
        else:
            out.append(Judged(x, "CHECKS FOUND", tuple(found)))
    return out


INTRO: Final = """# Rubric matrix

Scope: the organisers' published rubric. Status: generated from `web/src/judges.ts` and `docs/rubric_evidence.json`.

Generated by `scripts/rubric_matrix.py`; do not edit by hand. Each line of the rubric is shown with the page of the product that bears on
it, the checks that hold that page to what it says, and what the page does not show. A check counts when a test or check function, a test
file or a script of that name exists in the repository. A check that exists is not a check that passes: the suites say that.

"""


def render(judged: Sequence[Judged]) -> str:
    out = [INTRO, "| Verdict | Lines |\n|---|---|\n"]
    for verdict in VERDICTS:
        names = [j.line.line for j in judged if j.verdict == verdict]
        out.append(f"| {verdict}: {len(names)} | {', '.join(names) or '-'} |\n")
    out.append("\n| Track | Line | Points | Page | Checked by | Not shown |\n|---|---|---|---|---|---|\n")
    for j in judged:
        x = j.line
        checks = ", ".join(j.found + j.missing) or "-"
        out.append(f"| {TRACK_NAMES.get(x.group, x.group)} | {x.line} | {x.points} | {x.page} | {checks} | {x.limit.replace('|', '/')} |\n")
    return "".join(out)


def main(argv: list[str]) -> int:
    if argv and (argv[0].startswith("-") or len(argv) > 1):
        sys.stderr.write(f"usage: python {Path(__file__).name} [OUTPUT_FILE]\n")
        return 2
    out = Path(argv[0]) if argv else DEFAULT_OUT
    lines = read_lines((REPO / "web" / "src" / "judges.ts").read_text(encoding="utf-8"))
    evidence = json.loads((REPO / "docs" / "rubric_evidence.json").read_text(encoding="utf-8"))
    judged = judge(lines, evidence, REPO)
    out.write_text(render(judged), encoding="utf-8")
    return 0 if all(j.verdict == "CHECKS FOUND" for j in judged) else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
