#!/usr/bin/env python3
"""Write ``CONTRACT_MATRIX.md``: each numbered section of the forecast and settlement contract with the checks that hold the code to it.

The sections are read from the contract's own headings. The checks are named in ``docs/contract_evidence.json`` and looked up as a test or
check function, a test file or a script in the repository, by the same search as ``scripts/rubric_matrix.py``. A section may instead carry a
stated verdict (``NOT BUILT`` or ``OUTSIDE THIS REPOSITORY``) with its reason. A section that the file does not mention, a check that cannot
be found, or a section that does not exist is an error. The page says a check exists; it does not run it.

Usage: python scripts/contract_matrix.py [OUT.md]
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

REPO: Final = Path(__file__).resolve().parents[1]
CONTRACT: Final = REPO / "docs" / "specs" / "FORECAST_SETTLEMENT_CONTRACT.md"
DEFAULT_OUT: Final = REPO / "docs" / "specs" / "CONTRACT_MATRIX.md"
HEADING: Final = re.compile(r"^## (\d+)\. (.+?)\s*$", re.M)
STATED: Final = ("NOT BUILT", "OUTSIDE THIS REPOSITORY")
PARTLY: Final = "PARTLY BUILT"  # some of the section is built and checked, the rest is not: the reason says which
VERDICTS: Final = ("CHECKS FOUND", "CHECK NOT FOUND", PARTLY, *STATED, "NO CHECK NAMED")


def _rubric() -> Any:
    spec = importlib.util.spec_from_file_location("rubric_matrix", Path(__file__).with_name("rubric_matrix.py"))
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault("rubric_matrix", module)
    spec.loader.exec_module(module)
    return module


class ContractError(ValueError):
    """Evidence that does not fit the contract."""


@dataclass(frozen=True)
class Section:
    number: str
    title: str


@dataclass(frozen=True)
class Judged:
    section: Section
    verdict: str
    found: tuple[str, ...] = ()
    missing: tuple[str, ...] = ()
    reason: str = ""


def read_sections(text: str) -> list[Section]:
    """The numbered sections of the contract, in order."""
    return [Section(m.group(1), m.group(2)) for m in HEADING.finditer(text)]


def judge(sections: Sequence[Section], evidence: Mapping[str, Any], root: Path) -> list[Judged]:
    known = {s.number for s in sections}
    for number in evidence:
        if number not in known:
            raise ContractError(f"{number!r} is not a section of the contract")
    rubric = _rubric()
    text, stems = rubric._haystack(root)
    out: list[Judged] = []
    for section in sections:
        entry = evidence.get(section.number)
        if entry is None:
            out.append(Judged(section, "NO CHECK NAMED"))
        elif isinstance(entry, Mapping):
            verdict, reason = entry.get("verdict"), entry.get("reason")
            if verdict not in (*STATED, PARTLY):
                raise ContractError(f"section {section.number}: the verdict is one of {(*STATED, PARTLY)}")
            if not isinstance(reason, str) or not reason.strip():
                raise ContractError(f"section {section.number}: a stated verdict needs a reason")
            if verdict == PARTLY:
                names = entry.get("checks")
                if not isinstance(names, list) or not names or any(not isinstance(n, str) or not n.strip() for n in names):
                    raise ContractError(f"section {section.number}: a partly built section names the checks of what is built")
                missing = [n for n in names if not _exists(n, text, stems)]
                if missing:
                    raise ContractError(f"section {section.number}: checks that cannot be found: {missing}")
                out.append(Judged(section, PARTLY, tuple(names), reason=reason))
                continue
            out.append(Judged(section, str(verdict), reason=reason))
        else:
            names = list(entry)
            if not names or any(not isinstance(n, str) or not n.strip() for n in names):
                raise ContractError("a check is a name")
            found = [n for n in names if _exists(n, text, stems)]
            missing = [n for n in names if n not in found]
            out.append(Judged(section, "CHECK NOT FOUND" if missing else "CHECKS FOUND", tuple(found), tuple(missing)))
    return out


def _exists(name: str, text: str, stems: set[str]) -> bool:
    key = name.split(".")[-1]
    return name in stems or key in stems or re.search(rf"\b{re.escape(key)}\b", text) is not None


INTRO: Final = """# Contract matrix

Scope: the numbered sections of `FORECAST_SETTLEMENT_CONTRACT.md`.
Status: generated from the contract's headings and `docs/contract_evidence.json`.

Generated by `scripts/contract_matrix.py`; do not edit by hand. Each section is shown with the checks that hold the code to it.
A check counts when a test or check function, a test file or a script of that name exists in the repository.
A check that exists is not a check that passes: the suites say that. A section with no check named is NOT VERIFIED.
A section marked PARTLY BUILT, NOT BUILT or OUTSIDE THIS REPOSITORY says why.

"""


def render(judged: Sequence[Judged]) -> str:
    out = [INTRO, "| Verdict | Sections |\n|---|---|\n"]
    for verdict in VERDICTS:
        numbers = [j.section.number for j in judged if j.verdict == verdict]
        out.append(f"| {verdict}: {len(numbers)} | {', '.join(numbers) or '-'} |\n")
    out.append("\n| Section | Title | Verdict | Checked by, or why not |\n|---|---|---|---|\n")
    for j in judged:
        detail = j.reason or ", ".join(j.found + j.missing) or "-"
        if j.verdict == PARTLY:
            detail = f"{j.reason.rstrip('.')}. Checked by {', '.join(j.found)}"
        out.append(f"| {j.section.number} | {j.section.title.replace('|', '/')} | {j.verdict} | {detail.replace('|', '/')} |\n")
    return "".join(out)


def main(argv: list[str]) -> int:
    if argv and (argv[0].startswith("-") or len(argv) > 1):
        sys.stderr.write(f"usage: python {Path(__file__).name} [OUTPUT_FILE]\n")
        return 2
    out = Path(argv[0]) if argv else DEFAULT_OUT
    sections = read_sections(CONTRACT.read_text(encoding="utf-8"))
    evidence = json.loads((REPO / "docs" / "contract_evidence.json").read_text(encoding="utf-8"))
    judged = judge(sections, evidence, REPO)
    out.write_text(render(judged), encoding="utf-8")
    return 0 if all(j.verdict not in ("CHECK NOT FOUND", "NO CHECK NAMED") for j in judged) else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
