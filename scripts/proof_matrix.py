#!/usr/bin/env python3
"""Write ``docs/specs/PROOF_MATRIX.md``: every invariant of ``INVARIANTS.md`` with the evidence it names and what the
repository can confirm of it.

A row that says "tested" is believed only as far as the tests it names can be found: a name is looked for as a test or check function, as a
file in ``tests`` or as a file in the JavaScript suites. A row that names nothing the repository holds is not "tested" however it is worded
(a research model or an experiment is shown as such). The page confirms that a test exists. It does not run it: a test that exists is not a
test that passes, and the suites say that.

Usage: python scripts/proof_matrix.py [INVARIANTS.md [OUT.md]]
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Final

REPO: Final = Path(__file__).resolve().parents[1]
DEFAULT_IN: Final = REPO / "docs" / "specs" / "INVARIANTS.md"
DEFAULT_OUT: Final = REPO / "docs" / "specs" / "PROOF_MATRIX.md"
ROW: Final = re.compile(r"^\| ([A-Z]+-\d+) \|")
NAME: Final = re.compile(r"`([A-Za-z_][A-Za-z0-9_.]*)`")
SEARCH_DIRS: Final = ("tests", "verifier-js/test", "settlement-js/test", "web/test", "web/tools", "skills")
VERDICTS: Final = (
    "NAMED TESTS FOUND",
    "NAMED TESTS NOT FOUND",
    "RESEARCH ONLY",
    "PARTLY, WITH A NAMED GAP",
    "NOT BUILT",
    "NO TEST NAMED",
)


@dataclass(frozen=True)
class Row:
    ident: str
    invariant: str
    how: str
    status: str


@dataclass(frozen=True)
class Judged:
    row: Row
    verdict: str
    found: tuple[str, ...] = ()
    missing: tuple[str, ...] = ()


def read_rows(text: str) -> list[Row]:
    """The rows of every table that starts with an ID column; the last column is the status when the table has four, else empty."""
    rows: list[Row] = []
    for line in text.splitlines():
        if not ROW.match(line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 4:
            rows.append(Row(cells[0], cells[1], cells[2], "|".join(cells[3:]).strip()))
        elif len(cells) == 3:
            rows.append(Row(cells[0], cells[1], cells[2], ""))
        else:
            rows.append(Row(cells[0], cells[1] if len(cells) > 1 else "", "", ""))
    return rows


def _haystack(root: Path) -> tuple[str, set[str]]:
    text: list[str] = []
    stems: set[str] = set()
    for folder in SEARCH_DIRS:
        base = root / folder
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if path.suffix in (".py", ".mjs", ".ts", ".tsx") and ".venv" not in path.parts and "node_modules" not in path.parts:
                stems.add(path.stem)
                text.append(path.read_text(encoding="utf-8", errors="ignore"))
    return "\n".join(text), stems


def judge(row: Row, root: Path) -> Judged:
    status = row.status.lower()
    names = [n for n in NAME.findall(row.status) if not re.fullmatch(r"(E|CF|ADR|SS)\d+[a-z]?", n)]
    if names:
        text, stems = _haystack(root)
        found: list[str] = []
        missing: list[str] = []
        for name in names:
            key = name.split(".")[-1]
            ok = name in stems or key in stems or re.search(rf"\b{re.escape(key)}\b", text) is not None
            (found if ok else missing).append(key)
        if missing:
            return Judged(row, "NAMED TESTS NOT FOUND", tuple(found), tuple(missing))
        if status.startswith("partly"):
            return Judged(row, "PARTLY, WITH A NAMED GAP", tuple(found))
        return Judged(row, "NAMED TESTS FOUND", tuple(found))
    if status.startswith("partly"):
        return Judged(row, "PARTLY, WITH A NAMED GAP")
    if status.startswith("not built"):
        return Judged(row, "NOT BUILT")
    if "tested" in status or "model" in status or re.search(r"\bE\d+[a-z]?\b", row.status):
        return Judged(row, "RESEARCH ONLY")
    return Judged(row, "NO TEST NAMED")


INTRO: Final = """# Proof matrix

Scope: checkable properties. Status: generated from `INVARIANTS.md`.

Generated by `scripts/proof_matrix.py` from `INVARIANTS.md`; do not edit by hand. Each invariant is shown with what its own row
names and what the repository can confirm. A name counts when a test or check function, a test file or a script of that name
exists in the repository. The suites say whether a test passes; this page does not run them.

"""


def render(rows: list[Row], root: Path) -> str:
    judged = [judge(r, root) for r in rows]
    out = [INTRO, "A test that exists is not a test that passes.\n\n", "| Verdict | Rows |\n|---|---|\n"]
    for verdict in VERDICTS:
        ids = [j.row.ident for j in judged if j.verdict == verdict]
        out.append(f"| {verdict}: {len(ids)} | {', '.join(ids) or '-'} |\n")
    out.append("\n| ID | Invariant | Checked by | Verdict | Names found | Names not found |\n|---|---|---|---|---|---|\n")
    for j in judged:
        r = j.row
        found, missing = ", ".join(j.found) or "-", ", ".join(j.missing) or "-"
        out.append(f"| {r.ident} | {r.invariant.replace('|', '/')} | {r.how or '-'} | {j.verdict} | {found} | {missing} |\n")
    return "".join(out)


def main(argv: list[str]) -> int:
    source = Path(argv[0]) if argv else DEFAULT_IN
    out = Path(argv[1]) if len(argv) > 1 else DEFAULT_OUT
    out.write_text(render(read_rows(source.read_text(encoding="utf-8")), REPO), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
