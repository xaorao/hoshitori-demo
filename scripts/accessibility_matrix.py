#!/usr/bin/env python3
"""Write ``ACCESSIBILITY_MATRIX.md``: each binding criterion of the accessibility specification with the checks that hold the pages to it.

The criteria are the rows of the specification's own table of binding criteria. The checks are named in ``docs/accessibility_evidence.json``
and looked up as a test or check function, a test file or a script in the repository, by the same search as ``scripts/rubric_matrix.py``. A
criterion may instead carry a stated verdict (``NOT APPLICABLE`` or ``NOT TESTED``) with its reason. A criterion that the file does not
mention, a check that cannot be found or a criterion the specification does not have is an error. The page says a check exists; it does not
run it, and no person using a screen reader has been through the pages.

Usage: python scripts/accessibility_matrix.py [OUT.md]
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

REPO: Final = Path(__file__).resolve().parents[1]
SPEC: Final = REPO / "docs" / "specs" / "ACCESSIBILITY_SPEC.md"
DEFAULT_OUT: Final = REPO / "docs" / "specs" / "ACCESSIBILITY_MATRIX.md"
STATED: Final = ("NOT APPLICABLE", "NOT TESTED")
VERDICTS: Final = ("CHECKS FOUND", "CHECK NOT FOUND", *STATED, "NO CHECK NAMED")
_LABEL: Final = re.compile(r"^(\d+\.\d+\.\d+(?:, \d+\.\d+\.\d+)*)\s*(.*)$")


def _contract() -> Any:
    spec = importlib.util.spec_from_file_location("contract_matrix", Path(__file__).with_name("contract_matrix.py"))
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault("contract_matrix", module)
    spec.loader.exec_module(module)
    return module


class AccessibilityError(ValueError):
    """Evidence that does not fit the specification."""


@dataclass(frozen=True)
class Criterion:
    number: str
    title: str
    level: str


@dataclass(frozen=True)
class Judged:
    criterion: Criterion
    verdict: str
    found: tuple[str, ...] = ()
    missing: tuple[str, ...] = ()
    reason: str = ""


def read_criteria(text: str) -> list[Criterion]:
    """The rows of the table of binding criteria, in order."""
    start = text.find("## 1. Binding criteria")
    if start < 0:
        raise AccessibilityError("the specification has no table of binding criteria")
    end = text.find("\n## ", start + 4)
    out: list[Criterion] = []
    for line in text[start : end if end > 0 else len(text)].splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if not line.startswith("|") or len(cells) < 3:
            continue
        m = _LABEL.match(cells[0])
        if m is None:
            continue
        title = m.group(2) or cells[2][:60]
        out.append(Criterion(m.group(1), title, cells[1]))
    return out


def judge(criteria: Sequence[Criterion], evidence: Mapping[str, Any], root: Path) -> list[Judged]:
    known = {c.number for c in criteria}
    for number in evidence:
        if number not in known:
            raise AccessibilityError(f"{number!r} is not a criterion of the specification")
    contract = _contract()
    text, stems = contract._rubric()._haystack(root)
    out: list[Judged] = []
    for c in criteria:
        entry = evidence.get(c.number)
        if entry is None:
            out.append(Judged(c, "NO CHECK NAMED"))
        elif isinstance(entry, Mapping):
            verdict, reason = entry.get("verdict"), entry.get("reason")
            if verdict not in STATED:
                raise AccessibilityError(f"criterion {c.number}: the verdict is one of {STATED}")
            if not isinstance(reason, str) or not reason.strip():
                raise AccessibilityError(f"criterion {c.number}: a stated verdict needs a reason")
            out.append(Judged(c, str(verdict), reason=reason))
        else:
            names = list(entry)
            if not names or any(not isinstance(n, str) or not n.strip() for n in names):
                raise AccessibilityError("a check is a name")
            found = [n for n in names if contract._exists(n, text, stems)]
            missing = [n for n in names if n not in found]
            out.append(Judged(c, "CHECK NOT FOUND" if missing else "CHECKS FOUND", tuple(found), tuple(missing)))
    return out


INTRO: Final = """# Accessibility matrix

Scope: the binding criteria of `ACCESSIBILITY_SPEC.md`.
Status: generated from the specification's table and `docs/accessibility_evidence.json`.

Generated by `scripts/accessibility_matrix.py`; do not edit by hand. Each criterion is shown with the checks that hold the pages to it.
A check counts when a test or check function, a test file or a script of that name exists in the repository.
A check that exists is not a check that passes: the suites say that. A criterion with no check named is NOT VERIFIED.
NOT APPLICABLE and NOT TESTED say why no check exists. No person using a screen reader has been through the pages.

"""


def render(judged: Sequence[Judged]) -> str:
    out = [INTRO, "| Verdict | Criteria |\n|---|---|\n"]
    for verdict in VERDICTS:
        numbers = [j.criterion.number for j in judged if j.verdict == verdict]
        out.append(f"| {verdict}: {len(numbers)} | {'; '.join(numbers) or '-'} |\n")
    out.append("\n| Criterion | Subject | Level | Verdict | Checked by, or why not |\n|---|---|---|---|---|\n")
    for j in judged:
        c = j.criterion
        detail = j.reason or ", ".join(j.found + j.missing) or "-"
        out.append(f"| {c.number} | {c.title.replace('|', '/')} | {c.level} | {j.verdict} | {detail.replace('|', '/')} |\n")
    return "".join(out)


def main(argv: list[str]) -> int:
    out = Path(argv[0]) if argv else DEFAULT_OUT
    criteria = read_criteria(SPEC.read_text(encoding="utf-8"))
    evidence = json.loads((REPO / "docs" / "accessibility_evidence.json").read_text(encoding="utf-8"))
    judged = judge(criteria, evidence, REPO)
    out.write_text(render(judged), encoding="utf-8")
    return 0 if all(j.verdict not in ("CHECK NOT FOUND", "NO CHECK NAMED") for j in judged) else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
